const { chromium } = require('/Users/yh/.workbuddy-ai/binaries/node/workspace/node_modules/playwright-core')
const CHROME = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'
const BASE = 'http://127.0.0.1:5180'
const OUT = '/tmp/zj'

;(async () => {
  const browser = await chromium.launch({ executablePath: CHROME, headless: true })
  const logs = []

  // —— 新用户建档流程 ——
  const ctx = await browser.newContext({ viewport: { width: 430, height: 900 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
  const p = await ctx.newPage()
  p.on('pageerror', (e) => logs.push('ERR ' + e.message))
  await p.goto(BASE, { waitUntil: 'networkidle' })
  await p.waitForTimeout(700)
  await p.getByRole('button', { name: /作为新用户开始/ }).click()
  await p.waitForTimeout(1200)
  await p.screenshot({ path: `${OUT}/f-onboard.png`, fullPage: true })
  await p.locator('#pet-name').fill('布丁')
  await p.locator('input[type=date]').first().fill('2025-04-02')
  await p.getByRole('button', { name: /创建档案/ }).click()
  await p.waitForTimeout(1400)
  await p.screenshot({ path: `${OUT}/f-created.png`, fullPage: true })
  await p.getByRole('button', { name: /记录当前体重/ }).click()
  await p.waitForTimeout(600)
  await p.locator('#w').fill('3.4')
  await p.getByRole('button', { name: '保存记录' }).click()
  await p.waitForTimeout(1000)
  await p.getByRole('button', { name: '完成', exact: true }).click()
  await p.waitForTimeout(500)
  await p.screenshot({ path: `${OUT}/f-newhome.png`, fullPage: true })

  // —— 疫苗记录 + 设置提醒 ——
  await p.locator('.fab').click()
  await p.waitForTimeout(500)
  await p.getByRole('tab', { name: '疫苗' }).click()
  await p.waitForTimeout(300)
  await p.getByRole('button', { name: '猫三联', exact: true }).click()
  await p.locator('input[type=date]').first().fill('2026-10-18')
  await p.getByRole('button', { name: '保存记录' }).click()
  await p.waitForTimeout(1100)
  await p.screenshot({ path: `${OUT}/f-vaccine-done.png`, fullPage: true })
  await p.getByRole('button', { name: '保存提醒' }).click()
  await p.waitForTimeout(900)
  await p.getByRole('button', { name: '完成', exact: true }).click()
  await p.waitForTimeout(600)
  await p.goto(`${BASE}/#/health`, { waitUntil: 'networkidle' })
  await p.waitForTimeout(800)
  await p.screenshot({ path: `${OUT}/f-newhealth.png`, fullPage: true })

  // —— 分享到同城 ——
  await p.goto(`${BASE}/#/timeline`, { waitUntil: 'networkidle' })
  await p.waitForTimeout(700)
  await p.locator('.tl-actions button').first().click()
  await p.waitForTimeout(600)
  await p.locator('label').filter({ hasText: '同城可见' }).click()
  await p.getByRole('button', { name: '确认分享' }).click()
  await p.waitForTimeout(1400)
  await p.screenshot({ path: `${OUT}/f-sharetoast.png`, fullPage: true })
  await p.goto(`${BASE}/#/local`, { waitUntil: 'networkidle' })
  await p.waitForTimeout(800)
  await p.screenshot({ path: `${OUT}/f-localshared.png`, fullPage: true })

  // —— 评论 + 点赞 ——
  const likeBtn = p.locator('.post-action').first()
  await likeBtn.click()
  await p.waitForTimeout(300)
  const input = p.locator('.comment-input input').first()
  await input.fill('同城邻居来打个招呼，布丁好可爱。')
  await p.locator('.comment-input button').first().click()
  await p.waitForTimeout(800)
  await p.screenshot({ path: `${OUT}/f-comment.png`, fullPage: true })

  // —— 桌面：小组/活动 tab ——
  const dctx = await browser.newContext({ viewport: { width: 1440, height: 940 } })
  const dp = await dctx.newPage()
  dp.on('pageerror', (e) => logs.push('DERR ' + e.message))
  await dp.goto(BASE, { waitUntil: 'networkidle' })
  await dp.waitForTimeout(600)
  await dp.getByRole('button', { name: /使用演示档案进入/ }).click()
  await dp.waitForTimeout(1100)
  await dp.goto(`${BASE}/#/local`, { waitUntil: 'networkidle' })
  await dp.waitForTimeout(600)
  await dp.getByRole('button', { name: '品种小组' }).click()
  await dp.waitForTimeout(400)
  await dp.screenshot({ path: `${OUT}/f-groups.png` })
  await dp.getByRole('button', { name: '线下活动' }).click()
  await dp.waitForTimeout(400)
  await dp.screenshot({ path: `${OUT}/f-events.png` })
  await dp.goto(`${BASE}/#/messages`, { waitUntil: 'networkidle' })
  await dp.waitForTimeout(600)
  await dp.screenshot({ path: `${OUT}/f-messages.png` })
  await dp.goto(`${BASE}/#/settings`, { waitUntil: 'networkidle' })
  await dp.waitForTimeout(600)
  await dp.screenshot({ path: `${OUT}/f-settings.png`, fullPage: true })

  // 空状态：筛选无记录
  await dp.goto(`${BASE}/#/timeline`, { waitUntil: 'networkidle' })
  await dp.waitForTimeout(600)
  await dp.getByRole('button', { name: /日常/ }).first().click()
  await dp.waitForTimeout(400)
  await dp.screenshot({ path: `${OUT}/f-empty-filter.png` })

  console.log(logs.join('\n') || 'no page errors')
  await browser.close()
})().catch((e) => {
  console.error('FAILED', e.message)
  process.exit(1)
})
